CREATE TABLE llx_cpo_public_request_line (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_request bigint NOT NULL,
  line_key varchar(100) NOT NULL,
  position integer NOT NULL DEFAULT 0,
  source_product_id bigint NOT NULL,
  source_variation_id bigint NULL,
  requested_cartons integer NOT NULL,
  submitted_units_per_carton integer NULL,
  submitted_cbm_per_carton double NULL,
  submitted_gross_weight_kg double NULL,
  submitted_calculation_ready tinyint NOT NULL DEFAULT 0,
  submitted_missing_fields varchar(255) NULL,
  price_snapshot_json text NOT NULL,
  fk_product bigint NULL,
  verified_units_per_carton integer NULL,
  verified_cbm_per_carton double NULL,
  verified_gross_weight_kg double NULL,
  verified_packing_source varchar(32) NULL,
  packing_verified tinyint NOT NULL DEFAULT 0,
  review_status varchar(32) NOT NULL DEFAULT 'pending',
  staff_note varchar(1000) NULL,
  fk_user_creat integer NOT NULL,
  fk_user_modif integer NULL,
  date_creation datetime NOT NULL,
  date_modification datetime NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_cpo_request_line (entity, fk_request, line_key),
  KEY idx_cpo_request_line_request (entity, fk_request, position),
  KEY idx_cpo_request_line_product (entity, fk_product)
) ENGINE=innodb;
