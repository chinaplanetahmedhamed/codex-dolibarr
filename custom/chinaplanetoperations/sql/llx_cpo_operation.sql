CREATE TABLE llx_cpo_operation (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  ref varchar(64) NOT NULL,
  service_type varchar(32) NOT NULL,
  title varchar(255) NOT NULL,
  fk_soc integer NULL,
  fk_project integer NULL,
  fk_commande integer NULL,
  fk_user_assign integer NULL,
  fk_cpkanban_card integer NULL,
  fk_shipment integer NULL,
  priority varchar(12) NOT NULL DEFAULT 'normal',
  stage varchar(48) NOT NULL DEFAULT 'new',
  progress integer NOT NULL DEFAULT 0,
  waiting_on varchar(32) NOT NULL DEFAULT 'internal',
  next_action varchar(255) NULL,
  date_deadline datetime NULL,
  date_start datetime NULL,
  date_end datetime NULL,
  note_private mediumtext NULL,
  note_public mediumtext NULL,
  customer_visible tinyint NOT NULL DEFAULT 0,
  status smallint NOT NULL DEFAULT 1,
  fk_user_creat integer NOT NULL,
  fk_user_modif integer NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_cpo_operation_ref (entity, ref),
  KEY idx_cpo_operation_board (entity, status, stage, priority),
  KEY idx_cpo_operation_soc (entity, fk_soc, status),
  KEY idx_cpo_operation_owner (entity, fk_user_assign, status),
  KEY idx_cpo_operation_deadline (entity, date_deadline, status)
) ENGINE=innodb;
