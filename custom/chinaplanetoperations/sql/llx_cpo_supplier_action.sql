CREATE TABLE IF NOT EXISTS llx_cpo_supplier_action (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_operation bigint NOT NULL,
  action_type varchar(32) NOT NULL,
  request_token varchar(64) NOT NULL,
  object_key char(64) NULL,
  payload_hash char(64) NOT NULL,
  status varchar(24) NOT NULL DEFAULT 'preparing',
  fk_soc_customer bigint NOT NULL,
  fk_project bigint NOT NULL,
  fk_customer_order bigint NOT NULL,
  fk_supplier bigint NOT NULL,
  fk_supplier_order bigint NULL,
  fk_supplier_invoice bigint NULL,
  fk_supplier_payment bigint NULL,
  fk_bank bigint NULL,
  fk_bank_account bigint NULL,
  fk_payment_mode integer NULL,
  fk_allocation bigint NULL,
  payment_code varchar(16) NULL,
  payment_date date NULL,
  payment_reference varchar(255) NULL,
  amount decimal(24,8) NULL,
  currency_code varchar(3) NOT NULL,
  exchange_rate decimal(24,12) NOT NULL DEFAULT 1,
  error_code varchar(64) NULL,
  fk_user_creat integer NOT NULL,
  fk_user_modif integer NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_cpo_supplier_token (entity, request_token),
  UNIQUE KEY uk_cpo_supplier_object (entity, object_key),
  UNIQUE KEY uk_cpo_supplier_payment (entity, fk_supplier_payment),
  KEY idx_cpo_supplier_operation (entity, fk_operation, action_type, status),
  KEY idx_cpo_supplier_order (entity, fk_supplier_order, status),
  KEY idx_cpo_supplier_invoice (entity, fk_supplier_invoice, status),
  KEY idx_cpo_supplier_allocation (entity, fk_allocation, status)
) ENGINE=innodb;
