CREATE TABLE llx_cpo_qc_evidence (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_operation bigint NOT NULL,
  fk_checkpoint bigint NOT NULL,
  client_uuid char(36) NOT NULL,
  evidence_type varchar(16) NOT NULL,
  caption varchar(500) NULL,
  upload_status varchar(24) NOT NULL DEFAULT 'pending',
  review_status varchar(24) NOT NULL DEFAULT 'pending',
  customer_visible tinyint NOT NULL DEFAULT 0,
  upload_token_hash char(64) NULL,
  upload_owner integer NOT NULL,
  upload_expires_at datetime NULL,
  expected_size bigint NULL,
  chunk_size integer NULL,
  chunk_count integer NULL,
  chunk_manifest_json longtext NULL,
  original_name varchar(255) NOT NULL,
  original_stored_name varchar(255) NULL,
  original_mime varchar(128) NULL,
  original_size bigint NULL,
  original_sha256 char(64) NULL,
  safe_stored_name varchar(255) NULL,
  safe_mime varchar(128) NULL,
  safe_size bigint NULL,
  safe_sha256 char(64) NULL,
  revision integer NOT NULL DEFAULT 1,
  mutation_receipts_json longtext NULL,
  fk_user_creat integer NOT NULL,
  fk_user_review integer NULL,
  review_note text NULL,
  date_review datetime NULL,
  date_finalized datetime NULL,
  date_creation datetime NOT NULL,
  tms timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_cpo_qc_evidence_client (entity, fk_operation, client_uuid),
  UNIQUE KEY uk_cpo_qc_evidence_token (entity, upload_token_hash),
  KEY idx_cpo_qc_evidence_checkpoint (entity, fk_operation, fk_checkpoint, upload_status),
  KEY idx_cpo_qc_evidence_review (entity, fk_operation, review_status, customer_visible),
  KEY idx_cpo_qc_evidence_expiry (entity, upload_status, upload_expires_at)
) ENGINE=innodb;
