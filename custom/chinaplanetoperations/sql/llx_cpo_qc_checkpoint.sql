CREATE TABLE llx_cpo_qc_checkpoint (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_operation bigint NOT NULL,
  client_uuid char(36) NOT NULL,
  record_kind varchar(16) NOT NULL DEFAULT 'requirement',
  source_type varchar(16) NOT NULL DEFAULT 'manual',
  source_ref varchar(255) NULL,
  source_page integer NULL,
  source_confidence decimal(6,5) NULL,
  scope_type varchar(16) NOT NULL DEFAULT 'inspection',
  snapshot_line_key varchar(64) NULL,
  section_code varchar(64) NOT NULL DEFAULT 'general',
  section_label varchar(255) NOT NULL,
  requirement_text text NOT NULL,
  expected_value text NULL,
  tolerance_text text NULL,
  observation text NULL,
  result_code varchar(24) NOT NULL DEFAULT 'pending',
  severity varchar(16) NOT NULL DEFAULT 'none',
  mandatory tinyint NOT NULL DEFAULT 1,
  min_evidence integer NOT NULL DEFAULT 0,
  sample_size integer NULL,
  defects_critical integer NULL,
  defects_major integer NULL,
  defects_minor integer NULL,
  public_note text NULL,
  internal_note text NULL,
  position integer NOT NULL DEFAULT 0,
  revision integer NOT NULL DEFAULT 1,
  review_status varchar(24) NOT NULL DEFAULT 'pending',
  review_note text NULL,
  customer_visible tinyint NOT NULL DEFAULT 0,
  mutation_receipts_json longtext NULL,
  fk_user_creat integer NOT NULL,
  fk_user_modif integer NULL,
  fk_user_review integer NULL,
  date_review datetime NULL,
  date_creation datetime NOT NULL,
  tms timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_cpo_qc_checkpoint_client (entity, fk_operation, client_uuid),
  KEY idx_cpo_qc_checkpoint_list (entity, fk_operation, position, rowid),
  KEY idx_cpo_qc_checkpoint_review (entity, fk_operation, review_status, result_code),
  KEY idx_cpo_qc_checkpoint_scope (entity, fk_operation, scope_type, snapshot_line_key)
) ENGINE=innodb;
