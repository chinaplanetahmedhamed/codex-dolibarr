CREATE TABLE IF NOT EXISTS llx_cpo_billing_action (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_operation bigint NOT NULL,
  action_type varchar(24) NOT NULL,
  request_token varchar(64) NOT NULL,
  invoice_key char(64) NULL,
  payload_hash char(64) NOT NULL,
  status varchar(24) NOT NULL DEFAULT 'preparing',
  fk_soc bigint NOT NULL,
  fk_project bigint NULL,
  fk_order bigint NOT NULL,
  fk_invoice bigint NULL,
  fk_payment bigint NULL,
  fk_bank bigint NULL,
  fk_bank_account bigint NULL,
  fk_payment_mode integer NULL,
  payment_code varchar(16) NULL,
  payment_date date NULL,
  payment_reference varchar(255) NULL,
  amount decimal(24,8) NULL,
  currency_code varchar(3) NOT NULL,
  error_code varchar(64) NULL,
  fk_user_creat integer NOT NULL,
  fk_user_modif integer NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_cpo_billing_token (entity, request_token),
  UNIQUE KEY uk_cpo_billing_invoice_key (entity, invoice_key),
  UNIQUE KEY uk_cpo_billing_payment (entity, fk_payment),
  KEY idx_cpo_billing_operation (entity, fk_operation, action_type, status),
  KEY idx_cpo_billing_invoice (entity, fk_invoice, status)
) ENGINE=innodb;
