CREATE TABLE llx_cpo_sop_revision (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_sop bigint NOT NULL,
  revision_no integer NOT NULL,
  revision_status smallint NOT NULL DEFAULT 0,
  fk_category bigint NULL,
  country_code char(2) NULL,
  pol varchar(160) NULL,
  pod varchar(160) NULL,
  shipping_line varchar(128) NULL,
  service_type varchar(32) NOT NULL DEFAULT 'all',
  container_type varchar(32) NULL,
  incoterm varchar(16) NULL,
  cargo_type varchar(64) NULL,
  document_codes varchar(255) NULL,
  effective_date date NULL,
  fk_user_creat integer NOT NULL,
  fk_user_modif integer NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_cpo_soprev (entity, fk_sop, revision_no),
  KEY idx_cpo_soprev_current (entity, fk_sop, revision_status),
  KEY idx_cpo_soprev_context (entity, country_code, pod, shipping_line, service_type),
  KEY idx_cpo_soprev_category (entity, fk_category, cargo_type)
) ENGINE=innodb;
