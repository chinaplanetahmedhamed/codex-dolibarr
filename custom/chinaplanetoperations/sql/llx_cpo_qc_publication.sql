CREATE TABLE llx_cpo_qc_publication (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_operation bigint NOT NULL,
  fk_soc integer NOT NULL,
  public_uuid char(36) NOT NULL,
  version_no integer NOT NULL,
  is_current tinyint NOT NULL DEFAULT 1,
  overall_result varchar(40) NOT NULL,
  supervisor_override_reason text NULL,
  inspection_at datetime NULL,
  publication_json longtext NOT NULL,
  publication_sha256 char(64) NOT NULL,
  pdf_stored_name varchar(255) NULL,
  pdf_sha256 char(64) NULL,
  pdf_size bigint NULL,
  fk_user_review integer NOT NULL,
  fk_user_publish integer NOT NULL,
  date_review datetime NOT NULL,
  date_publication datetime NOT NULL,
  date_creation datetime NOT NULL,
  tms timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_cpo_qc_publication_version (entity, fk_operation, version_no),
  UNIQUE KEY uk_cpo_qc_publication_public (entity, public_uuid),
  KEY idx_cpo_qc_publication_current (entity, fk_operation, is_current, version_no),
  KEY idx_cpo_qc_publication_customer (entity, fk_soc, is_current, date_publication)
) ENGINE=innodb;
