CREATE TABLE llx_cpo_document (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_operation bigint NOT NULL,
  document_type varchar(64) NOT NULL,
  original_name varchar(255) NOT NULL,
  stored_name varchar(255) NOT NULL,
  mime_type varchar(128) NOT NULL,
  file_size bigint NOT NULL DEFAULT 0,
  version_no integer NOT NULL DEFAULT 1,
  parent_document_id bigint NULL,
  visibility varchar(24) NOT NULL DEFAULT 'internal',
  review_status varchar(32) NOT NULL DEFAULT 'not_received',
  review_comment text NULL,
  is_current tinyint NOT NULL DEFAULT 1,
  fk_user_creat integer NOT NULL,
  fk_user_review integer NULL,
  date_review datetime NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_cpo_document_operation (entity, fk_operation, document_type, is_current),
  KEY idx_cpo_document_visibility (entity, visibility, review_status),
  KEY idx_cpo_document_parent (entity, parent_document_id)
) ENGINE=innodb;
