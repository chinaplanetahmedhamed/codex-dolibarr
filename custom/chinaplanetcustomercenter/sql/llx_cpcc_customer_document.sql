CREATE TABLE IF NOT EXISTS llx_cpcc_customer_document (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_soc integer NOT NULL,
  fk_project integer NULL,
  fk_shipment integer NULL,
  source_element varchar(24) NOT NULL,
  source_id bigint NOT NULL,
  source_ref varchar(128) NOT NULL,
  relative_path varchar(512) NOT NULL,
  original_name varchar(255) NOT NULL,
  document_type varchar(64) NOT NULL DEFAULT 'other',
  mime_type varchar(128) NOT NULL,
  file_size bigint NOT NULL DEFAULT 0,
  file_sha256 char(64) NOT NULL,
  customer_visible tinyint NOT NULL DEFAULT 1,
  status tinyint NOT NULL DEFAULT 1,
  fk_user_publish integer NOT NULL,
  fk_user_modif integer NULL,
  date_publication datetime NOT NULL,
  date_unpublication datetime NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE INDEX uk_cpcc_customer_doc_file (entity, source_element, source_id, relative_path),
  INDEX idx_cpcc_customer_doc_owner (entity, fk_soc, customer_visible, status),
  INDEX idx_cpcc_customer_doc_project (entity, fk_soc, fk_project, status),
  INDEX idx_cpcc_customer_doc_shipment (entity, fk_soc, fk_shipment, status)
) ENGINE=innodb;
