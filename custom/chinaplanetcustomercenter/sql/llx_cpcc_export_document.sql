CREATE TABLE IF NOT EXISTS llx_cpcc_export_document (
  rowid integer AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_soc integer NOT NULL,
  fk_project integer NULL,
  fk_shipment integer NULL,
  document_type varchar(32) NOT NULL,
  ref varchar(64) NOT NULL,
  document_date date NOT NULL,
  currency_code varchar(3) NULL,
  total_amount decimal(24,8) NOT NULL DEFAULT 0,
  shipper_name varchar(255) NULL,
  consignee_name varchar(255) NULL,
  port_loading varchar(128) NULL,
  port_destination varchar(128) NULL,
  incoterm varchar(32) NULL,
  notes_public text NULL,
  customer_visible tinyint NOT NULL DEFAULT 1,
  status smallint NOT NULL DEFAULT 1,
  fk_user_creat integer NOT NULL,
  fk_user_modif integer NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE INDEX uk_cpcc_export_ref (entity, ref),
  INDEX idx_cpcc_export_soc (entity, fk_soc, document_date),
  INDEX idx_cpcc_export_project (fk_project),
  INDEX idx_cpcc_export_shipment (fk_shipment),
  INDEX idx_cpcc_export_visibility (status, customer_visible)
) ENGINE=innodb;
