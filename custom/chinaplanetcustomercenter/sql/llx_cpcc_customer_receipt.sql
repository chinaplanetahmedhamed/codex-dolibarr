CREATE TABLE IF NOT EXISTS llx_cpcc_customer_receipt (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_soc integer NOT NULL,
  receipt_date date NOT NULL,
  amount decimal(24,8) NOT NULL,
  currency_code varchar(3) NOT NULL,
  reference varchar(128) NULL,
  status varchar(16) NOT NULL DEFAULT 'pending',
  native_source_type varchar(32) NULL,
  native_source_id bigint NULL,
  request_key char(64) NOT NULL,
  payload_hash char(64) NOT NULL,
  note_private text NULL,
  fk_user_creat integer NOT NULL,
  fk_user_confirm integer NULL,
  fk_user_modif integer NULL,
  date_confirmation datetime NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_cpcc_receipt_request (entity, request_key),
  UNIQUE KEY uk_cpcc_receipt_native (entity, native_source_type, native_source_id),
  KEY idx_cpcc_receipt_customer (entity, fk_soc, currency_code, status),
  KEY idx_cpcc_receipt_date (entity, receipt_date)
) ENGINE=innodb;
