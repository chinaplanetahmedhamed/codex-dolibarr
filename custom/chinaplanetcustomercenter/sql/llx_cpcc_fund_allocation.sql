CREATE TABLE IF NOT EXISTS llx_cpcc_fund_allocation (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_receipt bigint NOT NULL,
  fk_soc integer NOT NULL,
  target_type varchar(32) NOT NULL,
  target_id bigint NOT NULL,
  fk_project integer NULL,
  fk_operation bigint NULL,
  fk_shipment bigint NULL,
  amount decimal(24,8) NOT NULL,
  currency_code varchar(3) NOT NULL,
  status varchar(16) NOT NULL DEFAULT 'reserved',
  disbursement_type varchar(32) NULL,
  disbursement_id bigint NULL,
  request_key char(64) NOT NULL,
  payload_hash char(64) NOT NULL,
  note_private text NULL,
  fk_user_creat integer NOT NULL,
  fk_user_settle integer NULL,
  fk_user_reverse integer NULL,
  date_settlement datetime NULL,
  date_reversal datetime NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_cpcc_allocation_request (entity, request_key),
  KEY idx_cpcc_allocation_receipt (entity, fk_receipt, status),
  KEY idx_cpcc_allocation_customer (entity, fk_soc, currency_code, status),
  KEY idx_cpcc_allocation_target (entity, target_type, target_id),
  KEY idx_cpcc_allocation_operation (entity, fk_operation),
  KEY idx_cpcc_allocation_shipment (entity, fk_shipment),
  KEY idx_cpcc_allocation_disbursement (entity, disbursement_type, disbursement_id)
) ENGINE=innodb;
