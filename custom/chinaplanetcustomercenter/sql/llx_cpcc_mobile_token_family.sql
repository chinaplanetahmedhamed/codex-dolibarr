CREATE TABLE IF NOT EXISTS llx_cpcc_mobile_token_family (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  family_public_id varchar(80) NOT NULL,
  entity integer NOT NULL,
  fk_user integer NOT NULL,
  fk_soc integer NOT NULL,
  device_id_hash char(64) NOT NULL,
  device_name varchar(80) NULL,
  current_generation integer NOT NULL DEFAULT 1,
  date_creation datetime NOT NULL,
  last_refresh_at datetime NOT NULL,
  inactivity_expires_at datetime NOT NULL,
  absolute_expires_at datetime NOT NULL,
  revoked_at datetime NULL,
  revoke_reason varchar(32) NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE INDEX uk_cpcc_mobile_family_public (family_public_id),
  INDEX idx_cpcc_mobile_family_owner (entity, fk_soc, fk_user),
  INDEX idx_cpcc_mobile_family_active (entity, revoked_at, absolute_expires_at)
) ENGINE=innodb;
