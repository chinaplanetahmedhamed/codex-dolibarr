CREATE TABLE llx_cpcc_portal_invitation (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_request bigint NOT NULL,
  fk_soc integer NOT NULL,
  fk_socpeople integer NOT NULL,
  fk_user integer NULL,
  email_hmac char(64) NOT NULL,
  token_hash char(64) NOT NULL,
  status varchar(16) NOT NULL DEFAULT 'pending',
  attempt_count integer NOT NULL DEFAULT 0,
  resend_count integer NOT NULL DEFAULT 0,
  expires_at datetime NOT NULL,
  last_attempt_at datetime NULL,
  accepted_at datetime NULL,
  revoked_at datetime NULL,
  fk_user_creat integer NOT NULL,
  fk_user_revoke integer NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_cpcc_invitation_token (entity, token_hash),
  KEY idx_cpcc_invitation_request (entity, fk_request, status),
  KEY idx_cpcc_invitation_email (entity, email_hmac, status),
  KEY idx_cpcc_invitation_expiry (entity, status, expires_at)
) ENGINE=innodb;
