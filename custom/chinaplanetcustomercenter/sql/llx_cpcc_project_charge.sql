CREATE TABLE IF NOT EXISTS llx_cpcc_project_charge (
  rowid integer AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_soc integer NOT NULL,
  fk_project integer NULL,
  fk_supplier integer NULL,
  charge_date date NOT NULL,
  category varchar(32) NOT NULL,
  label varchar(255) NOT NULL,
  supplier_label varchar(255) NULL,
  amount decimal(24,8) NOT NULL DEFAULT 0,
  currency_code varchar(3) NOT NULL,
  source_type varchar(64) NULL,
  source_id integer NULL,
  reference varchar(128) NULL,
  customer_visible tinyint NOT NULL DEFAULT 1,
  status smallint NOT NULL DEFAULT 1,
  fk_user_creat integer NOT NULL,
  fk_user_modif integer NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_cpcc_charge_soc (entity, fk_soc),
  INDEX idx_cpcc_charge_project (fk_project),
  INDEX idx_cpcc_charge_supplier (fk_supplier),
  INDEX idx_cpcc_charge_status (status, customer_visible)
) ENGINE=innodb;
