CREATE TABLE IF NOT EXISTS llx_cpcc_financial_entry (
  rowid integer AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_soc integer NOT NULL,
  fk_project integer NULL,
  fk_charge integer NULL,
  entry_date datetime NOT NULL,
  entry_type varchar(32) NOT NULL,
  direction char(1) NOT NULL,
  description varchar(255) NOT NULL,
  amount decimal(24,8) NOT NULL DEFAULT 0,
  currency_code varchar(3) NOT NULL,
  allocated_amount decimal(24,8) NULL,
  allocated_currency varchar(3) NULL,
  exchange_rate decimal(24,10) NULL,
  transfer_group varchar(64) NULL,
  reference varchar(128) NULL,
  bank_label varchar(128) NULL,
  source_type varchar(64) NULL,
  source_id integer NULL,
  proof_ecm_id integer NULL,
  customer_visible tinyint NOT NULL DEFAULT 1,
  status smallint NOT NULL DEFAULT 1,
  note_private text NULL,
  fk_user_creat integer NOT NULL,
  fk_user_modif integer NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_cpcc_entry_soc_date (entity, fk_soc, entry_date),
  INDEX idx_cpcc_entry_project (fk_project),
  INDEX idx_cpcc_entry_charge (fk_charge),
  INDEX idx_cpcc_entry_currency (currency_code),
  INDEX idx_cpcc_entry_transfer (transfer_group),
  INDEX idx_cpcc_entry_source (source_type, source_id),
  INDEX idx_cpcc_entry_status (status, customer_visible)
) ENGINE=innodb;
