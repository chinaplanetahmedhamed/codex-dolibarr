CREATE TABLE llx_chinaplanetsp_rule (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  label varchar(160) NOT NULL,
  public_label varchar(160) NULL,
  component_type varchar(24) NOT NULL DEFAULT 'other',
  container_type varchar(16) NULL,
  country_code char(2) NULL,
  pod varchar(160) NULL,
  pol varchar(128) NULL,
  shipping_line varchar(80) NULL,
  service_type varchar(16) NULL,
  incoterm varchar(8) NULL,
  cargo_type varchar(32) NULL,
  document_code varchar(32) NULL,
  calc_type varchar(12) NOT NULL DEFAULT 'fixed',
  amount decimal(24,8) NOT NULL DEFAULT 0,
  currency_code char(3) NOT NULL DEFAULT 'USD',
  priority integer NOT NULL DEFAULT 100,
  stackable smallint NOT NULL DEFAULT 1,
  date_start date NULL,
  date_end date NULL,
  notes_internal text NULL,
  status smallint NOT NULL DEFAULT 1,
  fk_user_creat integer NOT NULL,
  fk_user_modif integer NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_chinaplanetsp_rule_active (entity, status, component_type, priority),
  KEY idx_chinaplanetsp_rule_destination (entity, country_code, pod)
) ENGINE=innodb;
