CREATE TABLE llx_chinaplanetsp_sop_revision (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  fk_sop bigint NOT NULL,
  revision_no integer NOT NULL,
  revision_status smallint NOT NULL DEFAULT 0,
  title varchar(255) NOT NULL,
  title_ar varchar(255) NULL,
  fk_category bigint NULL,
  country_code char(2) NULL,
  pol varchar(160) NULL,
  pod varchar(160) NULL,
  shipping_line varchar(128) NULL,
  service_type varchar(16) NOT NULL DEFAULT 'all',
  container_type varchar(32) NULL,
  incoterm varchar(16) NULL,
  cargo_type varchar(64) NULL,
  document_codes varchar(255) NULL,
  applicability text NULL,
  required_information mediumtext NULL,
  procedure_steps mediumtext NULL,
  required_documents mediumtext NULL,
  warnings mediumtext NULL,
  escalation_instructions mediumtext NULL,
  internal_notes mediumtext NULL,
  responsible_department varchar(160) NULL,
  effective_date date NULL,
  change_summary varchar(512) NULL,
  fk_user_creat integer NOT NULL,
  fk_user_modif integer NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_chinaplanetsp_soprev (fk_sop, revision_no),
  KEY idx_chinaplanetsp_soprev_current (entity, fk_sop, revision_status),
  KEY idx_chinaplanetsp_soprev_context (entity, country_code, pod, shipping_line, service_type),
  KEY idx_chinaplanetsp_soprev_category (entity, fk_category, cargo_type)
) ENGINE=innodb;
