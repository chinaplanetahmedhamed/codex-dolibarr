CREATE TABLE llx_chinaplanetsp_batch (
  rowid bigint AUTO_INCREMENT PRIMARY KEY,
  entity integer NOT NULL DEFAULT 1,
  ref varchar(32) NOT NULL,
  source_name varchar(128) NOT NULL,
  original_name varchar(255) NOT NULL,
  stored_file varchar(512) NULL,
  file_hash char(64) NOT NULL,
  source_sheet varchar(128) NOT NULL,
  effective_date date NOT NULL,
  import_mode varchar(16) NOT NULL DEFAULT 'current',
  replacement_scope varchar(16) NOT NULL DEFAULT 'agent',
  ignore_below decimal(24,8) NOT NULL DEFAULT 1000,
  currency_code char(3) NOT NULL DEFAULT 'USD',
  total_rows integer NOT NULL DEFAULT 0,
  accepted_rows integer NOT NULL DEFAULT 0,
  ignored_rows integer NOT NULL DEFAULT 0,
  warning_count integer NOT NULL DEFAULT 0,
  status smallint NOT NULL DEFAULT 0,
  report_json mediumtext NULL,
  fk_user_creat integer NOT NULL,
  fk_user_modif integer NULL,
  date_creation datetime NOT NULL,
  tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_chinaplanetsp_batch_ref (entity, ref),
  KEY idx_chinaplanetsp_batch_date (entity, effective_date, status),
  KEY idx_chinaplanetsp_batch_hash (entity, file_hash)
) ENGINE=innodb;
